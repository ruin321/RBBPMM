export type MessageKey = keyof Messages

interface I18nValue {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (key: MessageKey, params?: Record<string, string | number>) => string
  locales: LocaleDef[]
}

const I18nContext = createContext<I18nValue>({
  locale: 'en',
  setLocale: () => undefined,
  t: (k) => en[k],
  locales: LOCALES
})

export function I18nProvider({ children }: { children: React.ReactNode }): React.JSX.Element {
  const [locale, setLocaleState] = useState<Locale>('en')

  useEffect(() => {
    let active = true
    void window.api.app.getLocale().then((l) => {
      if (active && LOCALES.some((x) => x.id === l)) {
        setLocaleState(l as Locale)
        document.documentElement.lang = l
      }
    })
    const unsub = window.api.app.onLocaleChanged((l) => {
      if (!active) return
      setLocaleState(l as Locale)
      document.documentElement.lang = l
    })
    return () => {
      active = false
      unsub()
    }
  }, [])

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l)
    document.documentElement.lang = l
    void window.api.app.setLocale(l)
  }, [])

  const t = useCallback(
    (key: MessageKey, params?: Record<string, string | number>): string => {
      let text = messages[locale][key] ?? en[key] ?? key
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          text = text.replace(`{${k}}`, String(v))
        }
      }
      return text
    },
    [locale]
  )

  const value: I18nValue = { locale, setLocale, t, locales: LOCALES }

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  return useContext(I18nContext)
}